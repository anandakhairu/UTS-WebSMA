const bulanIndonesia = {
  januari: 0,
  februari: 1,
  maret: 2,
  april: 3,
  mei: 4,
  juni: 5,
  juli: 6,
  agustus: 7,
  september: 8,
  oktober: 9,
  november: 10,
  desember: 11,
};

function tanggalKeTimestamp(tanggal, id) {
  const cocok = tanggal.match(/^(\d{1,2})\s+([a-z]+)\s+(\d{4})$/i);
  const hari = Number(cocok?.[1]);
  const bulan = cocok ? bulanIndonesia[cocok[2].toLowerCase()] : undefined;
  const tahun = Number(cocok?.[3]);

  if (bulan === undefined || !hari || !tahun) {
    throw new Error(`Format tanggal berita "${id}" tidak valid: "${tanggal}". Gunakan format "22 Juni 2026".`);
  }

  const timestamp = Date.UTC(tahun, bulan, hari);
  const tanggalValid = new Date(timestamp);
  if (
    tanggalValid.getUTCFullYear() !== tahun ||
    tanggalValid.getUTCMonth() !== bulan ||
    tanggalValid.getUTCDate() !== hari
  ) {
    throw new Error(`Tanggal berita "${id}" tidak valid: "${tanggal}".`);
  }

  return timestamp;
}

export const beritaTerbaru = [...beritaList].sort(
  (a, b) => tanggalKeTimestamp(b.tanggal, b.id) - tanggalKeTimestamp(a.tanggal, a.id),
);

export function getBerita(id) {
  return beritaList.find((b) => b.id === id);
}
